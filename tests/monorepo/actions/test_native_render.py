"""Local-only real CLI -> pinned OpenTofu/native provider proof.

Prior state is generated by OpenTofu mock-provider Apply, not cloud Apply.
Destroy plan uses the real selected AWS provider with refresh/network disabled.
The small ZIP is an explicit renderer unit fixture, not packaged application proof.
No rejected production Python renderer is imported.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
import zipfile

BP = Path(__file__).resolve().parents[3]
WORKSPACE = BP.parent
BINARY = os.environ.get('TRONADOR_CLI')
MODULE = BP / 'terraform/monorepo/modules/aws-lambda'


class ActualRendererNativeProof(unittest.TestCase):
    def test_lambda_handler_and_expired_payload_destroy(self):
        self.assertTrue(BINARY and Path(BINARY).is_file(), 'TRONADOR_CLI actual binary required; never silently skip')
        with tempfile.TemporaryDirectory(prefix='composite-native-render-') as temp:
            root = Path(temp).resolve()
            home = root / 'home'; home.mkdir(mode=0o700)
            env = {'PATH': os.environ['PATH'], 'HOME': str(home), 'CHECKPOINT_DISABLE': '1',
                   'HTTP_PROXY': 'http://127.0.0.1:9', 'HTTPS_PROXY': 'http://127.0.0.1:9',
                   'ALL_PROXY': 'http://127.0.0.1:9', 'NO_PROXY': '',
                   'AWS_EC2_METADATA_DISABLED': 'true', 'AWS_SHARED_CREDENTIALS_FILE': '/dev/null',
                   'AWS_CONFIG_FILE': '/dev/null', 'TF_IN_AUTOMATION': 'true'}
            def command(argv, *, data=None, cwd=root):
                result = subprocess.run(argv, input=json.dumps(data) if data is not None else None,
                                        text=True, capture_output=True, cwd=cwd, env=env,
                                        timeout=120, check=False)
                self.assertLess(len(result.stdout)+len(result.stderr), 16*1024*1024)
                self.assertEqual(result.returncode, 0, f'{argv}: {result.stderr}\n{result.stdout[-6000:]}')
                return result.stdout
            def cli(args, data=None):
                return json.loads(command([BINARY, 'components', 'operations', *args, '--json'], data=data))
            def private(name, value):
                file = root / name; file.write_text(json.dumps(value)); file.chmod(0o600); return file
            def output(name):
                directory = root / name; directory.mkdir(mode=0o700); return directory
            context = json.loads((WORKSPACE/'tronador-cli-v511/internal/components/testdata/operations/operation-context-frozen.json').read_text())
            component = context['plan']['components'][0]
            component.update(package={'kind':'function','provider':'aws','mode':'aws-zip','runtime':'provided.al2023','entryPoint':'bootstrap','architecture':'amd64','source':'.'}, workload={'kind':'function'}, preview={'mode':'container','source':'function','dockerfile':'Dockerfile','context':'.','adapter':'aws-lambda-rie','entryPoint':'bootstrap','port':8080,'healthPath':'/health','invokePath':'/invoke','invokeTest':{'requestBody':'{}','expectedStatus':200,'responseContains':'ok'}})
            context['plan']['targets'] = [{'id':'prod-run','environment':'prod','provider':'aws','authRef':'aws-prod','configDigest':'sha256:'+'2'*64,'kind':'aws.lambda','region':'us-east-1','functionName':'example','packageMode':'zip','alias':None,'runtime':'provided.al2023','iac':{'roleArn':'arn:aws:iam::123456789012:role/example','sourceBucket':'external-packages'},'readiness':{'deadlineSeconds':300,'intervalSeconds':5,'probe':{'kind':'lambda-invoke','requestBody':'{}','responseContains':'ok'}}}]
            context['providerIdentity']='123456789012'
            context['backend']['authRef']='aws-state'
            context['backendIdentity']={'provider':'aws','accountId':'123456789012'}
            context['authRefs']=['aws-prod','aws-state']
            catalog=json.loads(command(['yq','-o=json','-I=0','.',str(MODULE/'../../module-catalog.yaml')]))
            context['origin']['providerLockDigest']=catalog['modules']['aws-lambda']['providerLockDigest']
            context['origin']['moduleRevision']=catalog['modules']['aws-lambda']['revision']
            apply=cli(['plan','--operation','apply','--environment','prod','--target','prod-run','--component','api'],context)
            plan=private('apply.json',apply); derived=private('derived.json',{'component':component})
            payload=root/'unit-package.zip'
            with zipfile.ZipFile(payload,'w') as archive: archive.writestr('bootstrap','explicit non-deployable renderer unit fixture')
            descriptor=private('descriptor.json',{'kind':'function','format':'zip','digest':'sha256:'+hashlib.sha256(payload.read_bytes()).hexdigest(),'sizeBytes':payload.stat().st_size,'location':{'kind':'local','path':'unit-package.zip'},'sourceSha':context['plan']['headSha'],'builtVersion':context['plan']['version']})
            rendered=cli(['render','--plan',str(plan),'--module-root',str(MODULE),'--output',str(output('apply-render')),'--artifact',str(descriptor),'--payload',str(payload),'--derived',str(derived)])
            values=json.loads(Path(rendered['valuesPath']).read_text())
            self.assertEqual(values['package_handler'],component['package']['entryPoint'])
            native=root/'native'
            shutil.copytree(MODULE,native,ignore=shutil.ignore_patterns('.terraform','tests','*.tfstate*'))
            (native/'tests').mkdir()
            mock={'aws':{'mock_data':{'aws_caller_identity':{'defaults':{'account_id':'123456789012'}},'aws_iam_role':{'defaults':{'arn':context['plan']['targets'][0]['iac']['roleArn']}},'aws_s3_bucket':{'defaults':{'id':'external-packages'}}}}}
            test={'mock_provider':mock,'variables':values,'run':{'prior':{'command':'apply','assert':[{'condition':'${aws_lambda_function.component.handler == var.package_handler && var.package_handler == "bootstrap"}','error_message':'Derived package handler missing in actual native plan.'}]}}}
            (native/'tests/prior.tftest.json').write_text(json.dumps(test))
            self.assertEqual(json.loads(command(['tofu','version','-json']))['terraform_version'],'1.11.4')
            command(['tofu','init','-backend=false','-input=false','-lockfile=readonly',f'-plugin-dir={MODULE/".terraform/providers"}'],cwd=native)
            events=[json.loads(line) for line in command(['tofu','test','-json','-verbose'],cwd=native).splitlines()]
            view=next(event['test_state'] for event in events if event.get('type')=='test_state')
            records={}; previous=set()
            for resource in view['values']['root_module']['resources']:
                key=(resource['mode'],resource['type'],resource['name'])
                row=records.setdefault(key,{'mode':key[0],'type':key[1],'name':key[2],'provider':'provider["'+resource['provider_name']+'"]','instances':[]})
                instance={'schema_version':resource['schema_version'],'attributes':resource['values'],'sensitive_attributes':[]}
                if '[' in resource['address']: instance['index_key']=json.loads(resource['address'].split('[',1)[1][:-1])
                row['instances'].append(instance)
                if resource['mode']=='managed': previous.add(resource['address'])
            self.assertTrue(previous)
            state={'version':4,'terraform_version':'1.11.4','serial':1,'lineage':'11111111-1111-1111-1111-111111111111','outputs':{},'resources':list(records.values())}
            prior=private('prior.json',state)
            payload.unlink(); Path(values['artifact']['path']).unlink()
            self.assertFalse(payload.exists())
            context['historicalHandle']=apply['stateHandle']
            destroy=cli(['plan','--operation','destroy','--environment','prod','--target','prod-run','--component','api'],context)
            self.assertIsNone(destroy['inputs'])
            recovery=cli(['render','--plan',str(private('destroy.json',destroy)),'--module-root',str(MODULE),'--output',str(output('destroy-render')),'--derived',str(derived),'--historical-config',str(private('historical.json',context)),'--prior-state',str(prior)])
            self.assertTrue(recovery['evaluationOnly'])
            recovered=json.loads(Path(recovery['valuesPath']).read_text())
            self.assertEqual(recovered['package_handler'],'bootstrap')
            self.assertNotEqual(recovered['artifact']['path'],values['artifact']['path'])
            (native/'tests/prior.tftest.json').unlink()
            shutil.copyfile(prior,native/'terraform.tfstate')
            (native/'recovery.auto.tfvars.json').write_text(json.dumps(recovered))
            (native/'offline_override.tf').write_text('provider "aws" {\n access_key="offline-not-a-credential"\n secret_key="offline-not-a-credential"\n skip_credentials_validation=true\n skip_requesting_account_id=true\n skip_metadata_api_check=true\n skip_region_validation=true\n}\n')
            command(['tofu','plan','-destroy','-refresh=false','-input=false','-lock=false','-out=destroy.plan'],cwd=native)
            saved=json.loads(command(['tofu','show','-json','destroy.plan'],cwd=native))
            changes={row['address']:row['change']['actions'] for row in saved.get('resource_changes',[]) if row['mode']=='managed'}
            self.assertEqual(changes,{address:['delete'] for address in previous})
            print('NATIVE PROOF: real Go-derived Lambda handler; native mock-provider prior Apply; original payload deleted; selected AWS6.35.0 real-provider refresh-disabled destroy-only saved plan; no live cloud/auth/backend claim')

if __name__ == '__main__': unittest.main()
